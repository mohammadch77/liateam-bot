// Generates src/ui/icon/paths.ts from Material Symbols (Outlined, weight 400, Apache-2.0) — the icon set the
// Avina design uses — keeping only the icons listed here. Inline SVG instead of the 4 MB icon font.
//   npm run icons     (after adding a name below)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ICONS = [
  // header / navigation
  'menu',
  'search',
  'search_off',
  'person',
  'shopping_bag',
  'account_balance_wallet',
  'favorite',
  'home',
  'grid_view',
  'location_on',
  'local_shipping',
  'verified',
  'call',
  'mail',
  'bolt',
  'category',
  'history',
  'trending_up',
  // direction / controls
  'chevron_left',
  'chevron_right',
  'arrow_back',
  'arrow_forward',
  'keyboard_arrow_down',
  'close',
  'check',
  'add',
  'remove',
  'progress_activity',
  // product / feedback
  'star',
  'add_shopping_cart',
  'notifications',
  'inventory_2',
  'error',
  'warning',
  'check_circle',
  'wifi_off',
  'refresh',
  'lock',
  'assignment_return',
  'support_agent',
  'spa',
  'brush',
];
const FILLED = ['favorite', 'star', 'home', 'grid_view', 'shopping_bag', 'person', 'search'];

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const src = path.join(root, 'node_modules/@material-symbols/svg-400/outlined');
const pathOf = (file) => {
  const svg = fs.readFileSync(path.join(src, file), 'utf8');
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!d.length) throw new Error(`no path in ${file}`);
  return d.join(' ');
};

const entries = ICONS.map((n) => `  ${n}: '${pathOf(`${n}.svg`)}',`);
const filled = FILLED.map((n) => `  ${n}: '${pathOf(`${n}-fill.svg`)}',`);
const out = `// GENERATED by scripts/build-icons.mjs — do not edit. Material Symbols Outlined 400 (Apache-2.0), viewBox 0 -960 960 960.
export const ICON_PATHS = {
${entries.join('\n')}
} as const;

export const ICON_PATHS_FILLED: Partial<Record<keyof typeof ICON_PATHS, string>> = {
${filled.join('\n')}
};

export type IconName = keyof typeof ICON_PATHS;
`;
fs.writeFileSync(path.join(root, 'src/ui/icon/paths.ts'), out);
console.log(
  `icons: ${ICONS.length} (+${FILLED.length} filled) → src/ui/icon/paths.ts (${(out.length / 1024).toFixed(1)} KB)`,
);
